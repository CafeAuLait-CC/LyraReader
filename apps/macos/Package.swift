// swift-tools-version: 6.0
// LyraReader macOS native shell (SwiftPM, see docs/adr/0006).
//
// Layout:
//   LyraReaderFFI  — C module exposing the Rust C ABI (header committed by hand,
//                    see apps/macos/Sources/LyraReaderFFI/include/lyra_reader_ffi.h)
//   LyraReaderKit  — UI library (reusable by smoke scenarios / future test targets)
//   LyraReader     — executable app (@main)
//
// The Rust static library it links against is produced by:
//   ./scripts/build-rust.sh          → apps/macos/.rust/lib/liblyra_reader_ffi.a
// UniFFI-generated Swift bindings land in Sources/LyraReaderFFI/Generated once
// T0.8 is done (docs/05-ffi.md §8).

import PackageDescription

// Absolute path to this package, so the linker flag does not depend on the
// working directory SwiftPM happens to use. (String surgery rather than
// Foundation's URL: manifests do not import Foundation by default.)
let packageRoot = #filePath
    .split(separator: "/", omittingEmptySubsequences: false)
    .dropLast()
    .joined(separator: "/")

let package = Package(
    name: "LyraReader",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "LyraReader", targets: ["LyraReader"]),
        .library(name: "LyraReaderKit", targets: ["LyraReaderKit"]),
    ],
    targets: [
        .executableTarget(
            name: "LyraReaderChecks",
            dependencies: ["LyraReaderKit", "LyraReaderBindings"],
            path: "Checks"
        ),
        .target(
            name: "LyraReaderFFI",
            path: "Sources/LyraReaderFFI",
            publicHeadersPath: "include",
            linkerSettings: [
                // Name the archive explicitly: -l prefers a colocated dylib, whose
                // Cargo install name points back into target/debug/deps. That can
                // change under a running app and does not survive packaging.
                .unsafeFlags(["\(packageRoot)/.rust/lib/liblyra_reader_ffi.a"]),
                .linkedFramework("Metal"),
                .linkedFramework("QuartzCore"),
            ]
        ),
        // Generated by `scripts/build-rust.sh` (UniFFI); not committed.
        .target(
            name: "LyraReaderBindings",
            dependencies: ["LyraReaderFFI"],
            path: "Sources/LyraReaderBindings"
        ),
        .target(
            name: "LyraReaderKit",
            dependencies: ["LyraReaderFFI", "LyraReaderBindings"],
            path: "Sources/LyraReaderKit"
        ),
        .executableTarget(
            name: "LyraReader",
            dependencies: ["LyraReaderKit"],
            path: "Sources/LyraReader"
        ),
    ]
)
