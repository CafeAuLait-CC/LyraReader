#!/usr/bin/env python3
"""Generate public synthetic region records; this does not run Foundation or macOS."""
import base64
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "tests/fixtures/region-history"
DEST.mkdir(parents=True, exist_ok=True)

def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 8, 8, 8, 6, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress((b"\0" + bytes([80, 100, 220, 255]) * 8) * 8)) + chunk(b"IEND", b"")
entry = dict(id="00000001-1111-4222-8333-000000000001", documentKey="legacy-path-key",
             attachment=dict(page=0, rect=[[10.25, 20.5], [4, 4]], text="α/β\r\nA synthetic capture",
                             png=base64.b64encode(png).decode(), pixelWidth=8, pixelHeight=8,
                             captureScale=2, textTruncated=False),
             question="What does [p.999] mean?", answer="An unverified legacy page marker [p.999]",
             state="finished", createdAt=804000000.5, turns=[], knowledgeNote="A local note")
# Foundation's default object-key order is unspecified. Preserve the entire legacy source on
# a no-op; primitive escaping/number/rectangle bytes have independent assertions in Rust.
(DEST / "legacy-synthetic.json").write_text(json.dumps([entry], ensure_ascii=False, separators=(",", ":")).replace("/", "\\/") + "\n")
(DEST / "manifest.json").write_text(json.dumps({
    "origin": "Public synthetic data generated by scripts/make-region-history-fixtures.py",
    "license": "MIT", "foundation_execution": False,
    "geometry_contract_source": "https://github.com/swiftlang/swift-corelibs-foundation/blob/main/Sources/Foundation/NSGeometry.swift",
    "geometry_contract": "CGRect unkeyed container contains CGPoint [x,y] and CGSize [width,height]",
    "macos_generated_full_entry_golden": "pending"
}, indent=2) + "\n")
